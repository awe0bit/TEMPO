export function t(key: TranslationKey, variables: TranslationVariables = {}) {
  const dictionary: Record<TranslationKey, string> = language === 'zh-Hans' ? zhCN : en;
  return dictionary[key].replace(/\{(\w+)\}/g, (_, name: string) => String(variables[name] ?? `{${name}}`));
}

export function formatDate(value: Date | number | string, options: Intl.DateTimeFormatOptions) {
  const date = value instanceof Date ? value : new Date(value);
  return new Intl.DateTimeFormat(formattingLocale, options).format(date);
}

export function weekdayLabels() {
  const monday = new Date(2024, 0, 1);
  return Array.from({ length: 7 }, (_, index) => formatDate(new Date(2024, 0, 1 + index), { weekday: 'narrow' }));
}

export function relativeTime(value: Date | number | string) {
  const hours = Math.max(0, (Date.now() - new Date(value).getTime()) / 36e5);
  if (hours < 1) return t('rss.justNow');
  if (hours < 24) return t('rss.hoursAgo', { count: Math.floor(hours) });
  return t('rss.daysAgo', { count: Math.floor(hours / 24) });
}
