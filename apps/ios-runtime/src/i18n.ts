export type AppLanguage = 'zh-Hans' | 'en';

function resolveSystemLocale() {
  try {
    return Intl.DateTimeFormat().resolvedOptions().locale || 'zh-CN';
  } catch {
    return 'zh-CN';
  }
}

export const systemLocale = resolveSystemLocale();

function languageFor(locale: string): AppLanguage {
  return /^en(?:[-_]|$)/i.test(locale) ? 'en' : 'zh-Hans';
}

let language: AppLanguage = languageFor(systemLocale);
let formattingLocale = language === 'zh-Hans' ? 'zh-CN' : 'en-US';

export function setAppLocale(locale?: string) {
  language = languageFor(locale || systemLocale);
  formattingLocale = language === 'zh-Hans' ? 'zh-CN' : 'en-US';
}

